def cross_solver_figure(root: Path) -> PaperFigure:
    comparison = _read_json(root / CROSS_SOLVER)
    gate = comparison["optimum_gate"]
    data = {
        "outcome": str(comparison["outcome"]),
        "reference_objective": float(gate["reference_objective"]),
        "local_fit_objective": float(gate["local_fit_objective"]),
        "copasi_best_objective": float(gate["copasi_best_objective"]),
        "copasi_best_source": str(gate["copasi_best_source"]),
        "start_objectives": [float(value) for value in gate["start_objectives"]],
        "fungmod_objective_at_copasi_best": float(comparison["cross_check_at_copasi_best"]["fungmod_objective"]),
        "simulation_worst_abs_difference_over_sigma": float(comparison["simulation_gate"]["worst_abs_difference_over_sigma"]),
    }

    def draw(data: dict[str, Any], fig: Any) -> None:
        ax = fig.subplots()
        starts = sorted(data["start_objectives"])
        ax.scatter(range(1, len(starts) + 1), starts, color="tab:orange", label="COPASI fits from random starts")
        ax.axhline(data["reference_objective"], color="black", linewidth=1.2, label="FungMod recorded optimum")
        ax.axhline(data["local_fit_objective"], color="tab:blue", linestyle="--", linewidth=1.2, label="COPASI fit from FungMod's optimum")
        ax.set_xlabel("random start (sorted by objective)", fontsize=9)
        ax.set_ylabel("PEtab objective (negative log-likelihood up to a constant)", fontsize=9)
        ax.set_yscale("log")
        ax.tick_params(labelsize=8)
        ax.legend(fontsize=8)
        fig.tight_layout()

    return PaperFigure(
        name="figure_4_cross_solver",
        title="Cross-solver check of the recorded optimum in COPASI",
        caption=(
            "Objective of the exported three-condition PEtab problem at FungMod's recorded optimum, after COPASI's "
            "local fit from that point, and at the end of COPASI's fits from ten random starts (log axis). The recorded "
            "outcome is quoted in the manifest."
        ),
        data=data,
        draw=draw,
        sources=_sources(root, [CROSS_SOLVER]),
        key_numbers={
            "outcome": data["outcome"],
            "reference_objective": data["reference_objective"],
            "copasi_best_objective": data["copasi_best_objective"],
            "relative_difference": float(gate["relative_difference"]),
            "starts": len(data["start_objectives"]),
            "simulation_worst_abs_difference_over_sigma": data["simulation_worst_abs_difference_over_sigma"],
        },
    )


FIGURE_BUILDERS: tuple[Callable[[Path], PaperFigure], ...] = (
    holdout_figure,
    posterior_predictive_figure,
    criticism_screen_figure,
    cross_solver_figure,
)
FIGURE_SIZES = {
    "figure_1_cellulose_holdouts": (11.0, 10.0),
    "figure_2_posterior_predictive": (11.0, 10.0),
    "figure_3_criticism_screen": (11.0, 5.0),
    "figure_4_cross_solver": (6.0, 4.0),
}


def build_figures(root: Path) -> list[PaperFigure]:
    return [builder(root) for builder in FIGURE_BUILDERS]


def manifest_for(figures: Sequence[PaperFigure]) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "generator": GENERATOR,
        "figures": {
            figure.name: {
                "file": figure.file_name,
                "pdf_file": figure.pdf_file_name,
                "data_file": figure.data_file_name,
                "title": figure.title,
                "caption": figure.caption,
                "sources": figure.sources,
                "key_numbers": figure.key_numbers,
            }
            for figure in figures
        },
    }


def render(figure: PaperFigure, path: Path, *, fmt: str = "svg", dpi: int = 150) -> None:
    """Draw ``figure`` with matplotlib and save it; SVG and PDF metadata carry the generator, never a date."""

    import matplotlib

    matplotlib.use("Agg", force=False)
    from matplotlib.figure import Figure

    fig = Figure(figsize=FIGURE_SIZES[figure.name])
    figure.draw(figure.data, fig)
    if fmt == "svg":
        metadata: dict[str, Any] = {"Creator": GENERATOR, "Date": None}
    elif fmt == "pdf":
        metadata = {"Creator": GENERATOR, "CreationDate": None, "ModDate": None}
    else:
        metadata = {"Software": GENERATOR}
    fig.savefig(path, format=fmt, dpi=dpi, metadata=metadata)


def write_figures(root: Path, directory: Path | None = None) -> dict[str, Any]:
    """Regenerate every figure, its data file and the manifest under ``directory`` (default ``paper/figures``)."""

    target = root / PAPER_FIGURES_DIR if directory is None else directory
    target.mkdir(parents=True, exist_ok=True)
    figures = build_figures(root)
    for figure in figures:
        (target / figure.data_file_name).write_text(figure.rendered_data(), encoding="utf-8")
        render(figure, target / figure.file_name)
        render(figure, target / figure.pdf_file_name, fmt="pdf")
    manifest = manifest_for(figures)
    (target / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    return manifest


def check_figures(root: Path, directory: Path | None = None) -> list[str]:
    """Differences between the committed figure data and manifest and what the recorded results generate now."""

    target = root / PAPER_FIGURES_DIR if directory is None else directory
    problems: list[str] = []
    figures = build_figures(root)
    for figure in figures:
        data_path = target / figure.data_file_name
        if not data_path.exists():
            problems.append(f"{data_path} is missing")
        elif data_path.read_text(encoding="utf-8") != figure.rendered_data():
            problems.append(f"{data_path} differs from the data generated from the recorded results")
        svg_path = target / figure.file_name
        if not svg_path.exists():
            problems.append(f"{svg_path} is missing")
        elif GENERATOR not in svg_path.read_text(encoding="utf-8"):
            problems.append(f"{svg_path} does not carry the generator marker")
        pdf_path = target / figure.pdf_file_name
        if not pdf_path.exists():
            problems.append(f"{pdf_path} is missing")
        elif PDF_MARKER not in pdf_path.read_bytes():
            problems.append(f"{pdf_path} does not carry the generator marker")
    manifest_path = target / MANIFEST_NAME
    if not manifest_path.exists():
        problems.append(f"{manifest_path} is missing")
    else:
        recorded = json.loads(manifest_path.read_text(encoding="utf-8"))
        if recorded != manifest_for(figures):
            problems.append(f"{manifest_path} differs from the manifest generated from the recorded results")
        for name, entry in recorded.get("figures", {}).items():
            for source, digest in entry.get("sources", {}).items():
                path = root / source
                if not path.exists():
                    problems.append(f"{name}: source {source} is missing")
                elif file_digest(path) != digest:
                    problems.append(f"{name}: source {source} changed since the manifest was written")
    return problems


