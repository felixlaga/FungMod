# Table 4: stage B verdicts of the model-criticism study
# ---------------------------------------------------------------------------


def criticism_stage_b_table(root: Path) -> PaperTable:
    stage_b = root / CRITICISM_STAGE_B
    folders = sorted(path.parent for path in stage_b.glob("*/verdicts.json")) if stage_b.exists() else []
    if not folders:
        raise CultureBenchmarkError(f"No recorded stage B posterior under {stage_b}.")
    lines = [
        "| Model | Chain | Converged | R1 holdout | R2 multiplier interval | R3 added-parameter classes | Coverage (95%, with noise) | Outcome |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    sources: list[Path] = [gelain_criticism.PLAN_PATH]
    key: dict[str, Any] = {}
    for folder in folders:
        verdicts = _read_json(folder / "verdicts.json")
        calibration = _read_json(folder / "bayesian_calibration.json")
        coverage = _read_json(folder / "coverage.json")
        settings = calibration["settings"]
        diagnostics = calibration["diagnostics"]
        interval = verdicts["R2_multiplier_interval"]
        classes = verdicts["added_parameter_classes"]
        overall = coverage.get("overall", {}).get("all_observables")
        lines.append(
            f"| {folder.name} | {settings['n_walkers']} walkers x {settings['n_steps']} steps | {calibration['converged']} | "
            f"{verdicts['R1_holdout_support']} | [{interval[0]:.3g}, {interval[1]:.3g}] | "
            + ", ".join(f"`{name}` {klass}" for name, klass in classes.items())
            + f" | {overall['inside']}/{overall['observations']} | {verdicts['outcome']}{' (provisional)' if verdicts['provisional'] else ''} |"
        )
        for name in ("verdicts.json", "bayesian_calibration.json", "coverage.json"):
            sources.append((folder / name).relative_to(root))
        key[folder.name] = {
            "converged": calibration["converged"],
            "provisional": verdicts["provisional"],
            "R1_holdout_support": verdicts["R1_holdout_support"],
            "R2_adequacy": verdicts["R2_adequacy"],
            "R2_multiplier_interval": interval,
            "R3_identification": verdicts["R3_identification"],
            "added_parameter_classes": classes,
            "coverage_inside": overall["inside"],
            "coverage_observations": overall["observations"],
            "largest_autocorrelation_time": max(diagnostics["integrated_autocorrelation_time"]),
            "post_burn_in_steps": diagnostics["post_burn_in_steps"],
            "outcome": verdicts["outcome"],
        }
    lines.extend(["", "M0 is the baseline: its all-condition posterior is BAYES-001 (Table 2), which R1 and R3 do not address."])
    return PaperTable(
        name="table_4_criticism_stage_b",
        title="Stage B of the model-criticism study: adequacy, identification and coverage per added mechanism",
        markdown="\n".join(lines),
        sources=_sources(root, sources),
        key_numbers=key,
    )


