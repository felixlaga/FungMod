# Table 2: identifiability of the registry constants (BAYES-001)
# ---------------------------------------------------------------------------


def identifiability_table(root: Path) -> PaperTable:
    result = _read_json(root / BAYESIAN_RESULT)
    diagnostics = result["diagnostics"]
    order = list(result["summaries"])
    taus = diagnostics["integrated_autocorrelation_time"]
    ess = diagnostics["effective_sample_size"]
    lines = [
        "| Constant | Class | Posterior median | 95% interval | Prior box | Width / prior width (log10) | tau | ESS |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    widths = []
    for symbol, verdict in result["identifiability"].items():
        summary = result["summaries"][symbol]
        index = order.index(symbol)
        interval = verdict["credible_interval"]
        prior = verdict["prior_bounds"]
        lines.append(
            f"| `{_short(symbol)}` | {verdict['class']} | {summary['median']:.4g} | [{interval[0]:.3g}, {interval[1]:.3g}] | "
            f"[{prior[0]:.3g}, {prior[1]:.3g}] | {verdict['interval_width_fraction_of_prior']:.2f} | {taus[index]:.0f} | {ess[index]:.0f} |"
        )
        if verdict["class"] == "identified":
            widths.append(verdict["interval_width_fraction_of_prior"])
    multiplier = result["summaries"]["noise_scale:all_observables"]
    settings = result["settings"]
    lines.extend(
        [
            "",
            f"Shared noise multiplier: median {multiplier['median']:.3g}, 95% interval [{multiplier['lower']:.3g}, {multiplier['upper']:.3g}] "
            f"at an assumed 10 percent error. Sampler: {settings['n_walkers']} walkers, {settings['n_steps']} steps, "
            f"{settings['burn_in']} burn-in; converged by the declared rule: {result['converged']}; "
            f"mean acceptance {diagnostics['mean_acceptance_fraction']:.3f}; effective sample sizes {min(ess):.0f} to {max(ess):.0f}.",
        ]
    )
    classes = {_short(symbol): verdict["class"] for symbol, verdict in result["identifiability"].items()}
    return PaperTable(
        name="table_2_identifiability",
        title="Identifiability of the nine registry constants of the hydrolysis candidate (BAYES-001)",
        markdown="\n".join(lines),
        sources=_sources(root, [BAYESIAN_RESULT, gelain_bayesian.PLAN_PATH]),
        key_numbers={
            "classes": classes,
            "identified_count": sum(1 for klass in classes.values() if klass == "identified"),
            "identified_width_fraction_range": [min(widths), max(widths)] if widths else None,
            "noise_multiplier": {"median": multiplier["median"], "lower": multiplier["lower"], "upper": multiplier["upper"]},
            "converged": result["converged"],
            "walkers": settings["n_walkers"],
            "steps": settings["n_steps"],
            "burn_in": settings["burn_in"],
            "effective_sample_size_range": [min(ess), max(ess)],
            "mean_acceptance": diagnostics["mean_acceptance_fraction"],
        },
    )


# ---------------------------------------------------------------------------
# Table 3: stage A of the model-criticism study
# ---------------------------------------------------------------------------


def criticism_stage_a_table(root: Path) -> PaperTable:
    comparison = _read_json(root / CRITICISM_STAGE_A)
    models = comparison["models"]
    baseline = models[gelain_criticism.BASELINE_MODEL]["scenarios"]
    lines = [
        "| Model | Scenario | Mean normalized held-out MSE | Change vs M0 | Full rank everywhere | Screen (R1) |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    key: dict[str, Any] = {"plan_sha256": comparison["inputs"]["plan_sha256"], "optimiser": comparison["inputs"].get("optimiser"), "models": {}}
    for model_id, summary in models.items():
        key["models"][model_id] = {}
        for scenario, item in summary["scenarios"].items():
            screen = item["screen"]
            change = screen.get("relative_improvement")
            lines.append(
                f"| {model_id} | {scenario} | {item['mean_normalized_mse']:.4g} | {'' if change is None else _pct(change)} | "
                f"{item['full_rank_everywhere']} | {'passed' if screen['passed'] else 'failed: ' + '; '.join(screen['reasons'])} |"
            )
            key["models"][model_id][scenario] = {
                "mean_normalized_mse": item["mean_normalized_mse"],
                "relative_improvement": change,
                "screen_passed": screen["passed"],
                "per_observable_change": {
                    name: item["pooled_normalized_mse"][name] / baseline[scenario]["pooled_normalized_mse"][name] - 1.0
                    for name in item["pooled_normalized_mse"]
                }
                if model_id != gelain_criticism.BASELINE_MODEL
                else None,
            }
    observables = list(baseline["primary"]["pooled_normalized_mse"])
    lines.extend(["", "Per-observable pooled normalized held-out MSE, primary scenario:", "", "| Model | " + " | ".join(observables) + " |", "| --- | " + " | ".join("---" for _ in observables) + " |"])
    for model_id, summary in models.items():
        item = summary["scenarios"]["primary"]
        lines.append(f"| {model_id} | " + " | ".join(f"{item['pooled_normalized_mse'][name]:.4g}" for name in observables) + " |")
    return PaperTable(
        name="table_3_criticism_stage_a",
        title="Stage A of the preregistered model-criticism study: whole-condition holdouts and the R1 screen",
        markdown="\n".join(lines),
        sources=_sources(root, [CRITICISM_STAGE_A, gelain_criticism.PLAN_PATH]),
        key_numbers=key,
    )


