"""Tables of the software paper, generated from the recorded study results with a digest manifest.

Every number the paper quotes about the Gelain 2020 studies comes from a
checksummed result file in ``data/benchmarks``. This module turns those files
into the paper's tables (Markdown under ``paper/tables``) together with a
manifest that records, for each table, the source files and their SHA-256
digests and the key numbers the text uses. ``scripts/reproduce_paper.py``
calls it; ``tests/test_paper_tables.py`` checks that regenerating the tables
reproduces the committed files byte for byte and that the manifest digests
match the sources on disk.

Nothing here computes science: it reads recorded results and formats them.
The verification helpers at the end recompute a few cheap quantities from the
recorded artifacts (digest chains, the compiled-core objective at the recorded
cross-solver optimum, the stationarity of the recorded stage A baseline fit)
so that a reader can check the recorded files without re-running the studies.
"""

