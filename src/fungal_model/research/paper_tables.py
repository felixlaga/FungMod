def file_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read_json(path: Path) -> Any:
    if not path.exists():
        raise CultureBenchmarkError(f"Recorded result {path} is missing; the paper tables need it.")
    return json.loads(path.read_text(encoding="utf-8"))


def _short(symbol: str) -> str:
    return SHORT_SYMBOLS.get(symbol, symbol.replace("gelain_criticism_", ""))


def _pct(value: float) -> str:
    return f"{100.0 * value:+.1f}%"


@dataclass(frozen=True)
class PaperTable:
    """One table of the paper: its Markdown, the files it was read from and the numbers the text quotes."""

    name: str
    title: str
    markdown: str
    sources: dict[str, str] = field(default_factory=dict)
    key_numbers: dict[str, Any] = field(default_factory=dict)

    @property
    def file_name(self) -> str:
        return f"{self.name}.md"

    def rendered(self) -> str:
        return f"<!-- generated by scripts/reproduce_paper.py tables; do not edit -->\n# {self.title}\n\n{self.markdown}\n"


def _sources(root: Path, paths: Sequence[Path]) -> dict[str, str]:
    return {path.as_posix(): file_digest(root / path) for path in paths}


# ---------------------------------------------------------------------------
# Table 1: whole-condition holdouts of the joint benchmark (v2)
# ---------------------------------------------------------------------------


def joint_benchmark_table(root: Path) -> PaperTable:
    report = _read_json(root / JOINT_REPORT)
    rows = report["comparison"]
    lines = [
        "| Family | Model | Scenario | Parameters | Practical rank | Mean normalized held-out MSE | Complexity screen |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['family']} | {row['model']} | {row['scenario']} | {row['parameter_count']} | {row['practical_rank']} | "
            f"{row['mean_normalized_mse']:.4g} | {'passed' if row['complexity_screen_passed'] else 'failed'} |"
        )
    primary = {(row["family"], row["model"]): row for row in rows if row["scenario"] == "primary"}
    hydrolysis = primary[("cellulose", "hydrolysis")]
    published = primary[("cellulose", "published")]
    lines.extend(
        [
            "",
            f"Folds that passed the numerical checks: {report['successful_numerically_checked_folds']} of {report['folds']}; "
            f"optimiser starts that failed: {report['failed_starts']} of {report['optimizer_starts']}. "
            f"Validated: {report['validated']} (retrospective comparison on published means).",
        ]
    )
    return PaperTable(
        name="table_1_joint_holdouts",
        title="Whole-condition holdouts of the joint Gelain 2020 benchmark (v2)",
        markdown="\n".join(lines),
        sources=_sources(root, [JOINT_REPORT, JOINT_PLAN]),
        key_numbers={
            "hydrolysis_primary_mean_normalized_mse": hydrolysis["mean_normalized_mse"],
            "published_primary_mean_normalized_mse": published["mean_normalized_mse"],
            "published_parameter_count": published["parameter_count"],
            "published_practical_rank": published["practical_rank"],
            "published_screen_passed": published["complexity_screen_passed"],
            "hydrolysis_screen_passed_by_scenario": {
                row["scenario"]: row["complexity_screen_passed"] for row in rows if (row["family"], row["model"]) == ("cellulose", "hydrolysis")
            },
            "folds_numerically_checked": report["successful_numerically_checked_folds"],
            "folds": report["folds"],
            "failed_starts": report["failed_starts"],
            "optimizer_starts": report["optimizer_starts"],
            "validated": report["validated"],
        },
    )


