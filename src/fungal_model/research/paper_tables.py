TABLE_BUILDERS: tuple[Callable[[Path], PaperTable], ...] = (
    joint_benchmark_table,
    identifiability_table,
    criticism_stage_a_table,
    criticism_stage_b_table,
    cross_solver_table,
)


def build_tables(root: Path) -> list[PaperTable]:
    return [builder(root) for builder in TABLE_BUILDERS]


def manifest_for(tables: Sequence[PaperTable]) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "generator": "fungal_model.research.paper_tables (scripts/reproduce_paper.py tables)",
        "tables": {
            table.name: {
                "file": table.file_name,
                "title": table.title,
                "sources": table.sources,
                "key_numbers": table.key_numbers,
            }
            for table in tables
        },
    }


def write_tables(root: Path, directory: Path | None = None) -> dict[str, Any]:
    """Regenerate every table and the manifest under ``directory`` (default ``paper/tables``)."""

    target = root / PAPER_TABLES_DIR if directory is None else directory
    target.mkdir(parents=True, exist_ok=True)
    tables = build_tables(root)
    for table in tables:
        (target / table.file_name).write_text(table.rendered(), encoding="utf-8")
    manifest = manifest_for(tables)
    (target / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    return manifest


def check_tables(root: Path, directory: Path | None = None) -> list[str]:
    """Differences between the committed tables and what the recorded results generate now (empty when consistent)."""

    target = root / PAPER_TABLES_DIR if directory is None else directory
    problems: list[str] = []
    tables = build_tables(root)
    for table in tables:
        path = target / table.file_name
        if not path.exists():
            problems.append(f"{path} is missing")
        elif path.read_text(encoding="utf-8") != table.rendered():
            problems.append(f"{path} differs from the table generated from the recorded results")
    manifest_path = target / MANIFEST_NAME
    if not manifest_path.exists():
        problems.append(f"{manifest_path} is missing")
    else:
        recorded = json.loads(manifest_path.read_text(encoding="utf-8"))
        if recorded != manifest_for(tables):
            problems.append(f"{manifest_path} differs from the manifest generated from the recorded results")
        for name, entry in recorded.get("tables", {}).items():
            for source, digest in entry.get("sources", {}).items():
                path = root / source
                if not path.exists():
                    problems.append(f"{name}: source {source} is missing")
                elif file_digest(path) != digest:
                    problems.append(f"{name}: source {source} changed since the manifest was written")
    return problems


# ---------------------------------------------------------------------------
# Cheap verification of the recorded results (no study is re-run)
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Check:
    name: str
    passed: bool
    detail: str


def _digest_chain(plan: Mapping[str, Any], plan_path: Path) -> set[str]:
    return {file_digest(plan_path), *(entry["previous_sha256"] for entry in plan.get("amendments", []))}


def verify_recorded_results(root: Path, *, registry: Any = None) -> list[Check]:
    """Recompute what can be recomputed in minutes from the recorded artifacts.

    Digest chains of every study against its plan; the frozen held-out
    predictions and the stage B artifact digests; the cross-solver plan's
    sources; the compiled-core objective at the recorded cross-solver
    optimum (must equal the recorded reference to 1e-7); and the projected
    cost gradient of the recorded stage A baseline fit (must be below 1e-2
    in log space, the stationarity the amendment 3 re-run established).
    """

    checks: list[Check] = []

    def record(name: str, passed: bool, detail: str) -> None:
        checks.append(Check(name, bool(passed), detail))

    # criticism plan chain and stage A files
    plan = gelain_criticism.load_plan(root)
    chain = _digest_chain(plan, root / gelain_criticism.PLAN_PATH)
    comparison = _read_json(root / CRITICISM_STAGE_A)
    record("criticism stage A cites the plan chain", comparison["inputs"]["plan_sha256"] in chain, comparison["inputs"]["plan_sha256"][:12])
    frozen_ok, frozen_count = True, 0
    for model_id in comparison["models"]:
        for scenario in comparison["models"][model_id]["scenarios"]:
            folds = _read_json(root / CRITICISM_STAGE_A.parent / model_id / f"folds_{scenario}.json")
            for fold in folds:
                frozen_path = root / CRITICISM_STAGE_A.parent.parent / fold["frozen_prediction_file"]
                frozen_count += 1
                if not frozen_path.exists() or file_digest(frozen_path) != fold["frozen_prediction_sha256"]:
                    frozen_ok = False
    record("stage A frozen held-out predictions match their recorded digests", frozen_ok, f"{frozen_count} files")
    stage_b = root / CRITICISM_STAGE_B
    artifacts_ok, artifact_count = True, 0
    for artifacts_path in sorted(stage_b.glob("**/artifacts.json")) if stage_b.exists() else []:
        folder = artifacts_path.parent
        inputs = _read_json(folder / "inputs.json")
        if inputs["plan_sha256"] not in chain:
            artifacts_ok = False
        for name, digest in _read_json(artifacts_path).items():
            if name == "artifacts.json":
                continue
            artifact_count += 1
            if not (folder / name).exists() or file_digest(folder / name) != digest:
                artifacts_ok = False
    record("stage B artifacts match their recorded digests and cite the plan chain", artifacts_ok, f"{artifact_count} files")

    # Bayesian study
    bayesian_inputs = _read_json(root / gelain_bayesian.PLAN_PATH.parent / "results" / "inputs.json")
    bayesian_plan_digest = file_digest(root / gelain_bayesian.PLAN_PATH)
    record("BAYES-001 cites the current Bayesian plan", bayesian_inputs["plan_sha256"] == bayesian_plan_digest, bayesian_plan_digest[:12])
    bayesian_artifacts = _read_json(root / gelain_bayesian.PLAN_PATH.parent / "results" / "artifacts.json")
    ok = all(
        file_digest(root / gelain_bayesian.PLAN_PATH.parent / "results" / name) == digest
        for name, digest in bayesian_artifacts.items()
        if name != "artifacts.json" and (root / gelain_bayesian.PLAN_PATH.parent / "results" / name).exists()
    )
    record("BAYES-001 artifacts match their recorded digests", ok, f"{len(bayesian_artifacts)} entries")

    # cross-solver plan and the compiled-core objective at the recorded optimum
    petab_plan = gelain_petab.load_plan(root)
    try:
        gelain_petab.verify_sources(root, petab_plan)
        record("cross-solver plan sources carry their frozen digests", True, "4 sources")
    except CultureBenchmarkError as exc:
        record("cross-solver plan sources carry their frozen digests", False, str(exc))
    cross = _read_json(root / CROSS_SOLVER)
    record("cross-solver result cites the current plan", cross["plan_sha256"] == file_digest(root / gelain_petab.PLAN_PATH), cross["plan_sha256"][:12])
    import tempfile

    with tempfile.TemporaryDirectory() as temporary:
        problem = gelain_petab.build_problem(root, Path(temporary), registry=registry)
        objective = problem.fungmod_objective()
    reference = cross["optimum_gate"]["reference_objective"]
    relative = abs(objective - reference) / reference
    record("compiled-core objective at the recorded cross-solver optimum", relative <= 1e-7, f"{objective:.9g} against {reference:.9g} (relative {relative:.1e})")

    # stationarity of the recorded stage A baseline fit
    fit = gelain_petab.reference_fit(root, petab_plan)
    gradient_norm = projected_gradient_norm(root, fit, registry=registry)
    record("recorded stage A baseline fit is stationary (projected gradient norm in log space)", gradient_norm < 1e-2, f"{gradient_norm:.2e}")
    return checks


def projected_gradient_norm(root: Path, fit: Mapping[str, Any], *, registry: Any = None) -> float:
    """Norm of the stage A primary cost gradient at a recorded M0 fit, with outward components on active bounds removed."""

    from fungal_model.registry import load_registry

    plan = gelain_criticism.load_plan(root)
    bayesian_plan = gelain_bayesian.load_plan(root)
    store = registry if registry is not None else load_registry(root / gelain_criticism.REGISTRY_INDEX)
    conditions = gelain_criticism.observed_conditions(root, plan)
    variant = gelain_criticism.model_variants(plan)[gelain_criticism.BASELINE_MODEL]
    predictor = gelain_criticism.build_predictor(store, plan, gelain_criticism.BASELINE_MODEL, bayesian_plan=bayesian_plan)
    scales = gelain_criticism.training_scales(conditions)
    free = list(variant.parameters)
    lower, upper = variant.log_bounds()

    def cost(log_values: np.ndarray) -> float:
        values = {spec.symbol: float(value) for spec, value in zip(free, np.exp(log_values), strict=True)}
        config_values = variant.config_values(values)
        residuals = np.concatenate(
            [((predictor.predict_values(config_values, c.condition_id, c.times) - c.observed) / scales).ravel() for c in conditions]
        )
        return 0.5 * float(residuals @ residuals)

    point = np.log([float(entry["value"]) for entry in fit["parameters"]])
    step = float(plan["stage_A_least_squares"]["optimiser"]["log_parameter_difference_step"])
    gradient = np.zeros_like(point)
    for index in range(point.size):
        unit = np.zeros_like(point)
        unit[index] = step
        gradient[index] = (cost(point + unit) - cost(point - unit)) / (2.0 * step)
    on_lower = (point - lower < 1e-6) & (gradient > 0.0)
    on_upper = (upper - point < 1e-6) & (gradient < 0.0)
    return float(np.linalg.norm(np.where(on_lower | on_upper, 0.0, gradient)))


